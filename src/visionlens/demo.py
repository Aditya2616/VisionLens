"""Record the static demo: real runs of the pipeline saved as JSON next to their videos.

`docs/demo/` is what the GitHub Pages site (and the local server) replays. Every file there is
produced by this module from an actual run on this machine; nothing is hand-edited.
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

import cv2

from .describe import make_describer
from .detect import load_detector
from .pipeline import Pipeline, PipelineConfig, analyze_image
from .runner import analyze_file
from .sprite import write_sprite
from .synth import NoiseConfig, NoisyOracle, make_scene, render_video
from .sysutil import cpu_name, gpu_name, limit_threads
from .video import iter_frames


def _ground_truth(scene) -> list[list[dict]]:
    return [
        [
            {"id": g, "box": [round(v, 1) for v in b], "cls": c, "vis": round(v, 2)}
            for g, b, v, c in scene.gt(i)
            if v >= 0.25
        ]
        for i in range(scene.n_frames)
    ]


def _write_json(path: Path, res) -> None:
    path.write_text(res.model_dump_json(), "utf-8")


def record_demo(
    out_dir: Path,
    detector: str,
    stride: int,
    threads: int | None,
    describer: str,
    names: list[str] | None = None,
    machine_note: str = "",
) -> None:
    n_threads = limit_threads(threads)
    manifest_path = out_dir.parent.parent / "data" / "samples.json"
    samples = json.loads(manifest_path.read_text("utf-8")) if manifest_path.exists() else {}
    clips: list[dict] = []
    det = load_detector(detector, 640)
    llm = make_describer(describer)
    want = set(names) if names else None

    for name, info in samples.items():
        if want and name not in want:
            continue
        print("recording", name, flush=True)
        res = analyze_file(
            out_dir / info["file"],
            det,
            PipelineConfig(stride=stride),
            llm,
            threads=n_threads,
            machine_note=machine_note,
            name=name,
        )
        res.meta.recorded = True
        _write_json(out_dir / f"{name}.json", res)
        clips.append(
            {
                "id": name,
                "label": info["label"],
                "blurb": info["blurb"],
                "kind": "video",
                "json": f"{name}.json",
                "video": info["file"],
                "sprite": info["sprite"],
                "sprite_info": info["sprite_info"],
                "width": info["width"],
                "height": info["height"],
                "source": info["source"],
                "simulated": False,
            }
        )

    if not want or "synthetic" in want:
        print("recording synthetic", flush=True)
        scene = make_scene("street", seed=1, seconds=8.0, fps=10.0, size=(480, 270))
        render_video(scene, str(out_dir / "synthetic.webm"))
        frames = [(i / scene.fps, scene.render(i)) for i in range(scene.n_frames)]
        sprite = write_sprite(
            frames, out_dir / "synthetic_sprite.jpg", fps=5.0, thumb_w=320, quality=60
        )
        pipe = Pipeline(NoisyOracle(scene, NoiseConfig.level(1, 1)), PipelineConfig(stride=stride))
        for _ in pipe.process((i, i / scene.fps, f) for i, (_, f) in enumerate(frames)):
            pass
        res = pipe.finish(
            "synthetic",
            scene.width,
            scene.height,
            scene.fps,
            llm,
            None,
            threads=n_threads,
            machine_note=machine_note,
        )
        res.meta.recorded = True
        res.meta.detector = "simulated detector (ground truth plus noise)"
        res.meta.note = (
            "Synthetic scene rendered by VisionLens. The detections are the exact "
            "ground truth with injected noise, not a neural detector; the tracker, "
            "events and description are the real ones."
        )
        res.ground_truth = _ground_truth(scene)
        _write_json(out_dir / "synthetic.json", res)
        clips.append(
            {
                "id": "synthetic",
                "label": "Synthetic street, with ground truth",
                "blurb": "A rendered scene with a simulated detector. Toggle ground truth to compare.",
                "kind": "video",
                "json": "synthetic.json",
                "video": "synthetic.webm",
                "sprite": "synthetic_sprite.jpg",
                "sprite_info": sprite,
                "width": scene.width,
                "height": scene.height,
                "simulated": True,
                "source": {
                    "title": "Generated by VisionLens (visionlens.synth)",
                    "license": "MIT",
                    "author": "Aditya Jain",
                    "page": "",
                },
            }
        )

    if (not want or "still" in want) and (out_dir / "traffic.webm").exists():
        print("recording still", flush=True)
        for _i, _t, frame in iter_frames(
            out_dir / "traffic.webm",
            max_width=640,
            target_fps=15,
            start_seconds=5.0,
            max_seconds=0.2,
        ):
            cv2.imwrite(str(out_dir / "still.jpg"), frame, [cv2.IMWRITE_JPEG_QUALITY, 80])
            break
        res = analyze_image(det, cv2.imread(str(out_dir / "still.jpg")), "still")
        res.meta.recorded = True
        _write_json(out_dir / "still.json", res)
        clips.append(
            {
                "id": "still",
                "label": "Single image",
                "blurb": "Detection on one frame (no tracking).",
                "kind": "image",
                "json": "still.json",
                "video": "still.jpg",
                "width": 640,
                "height": res.meta.height,
                "simulated": False,
                "source": {**samples.get("traffic", {}).get("source", {}), "note": "frame at 5 s"},
            }
        )

    index_path = out_dir / "index.json"
    old = (
        json.loads(index_path.read_text("utf-8")) if index_path.exists() and want else {"clips": []}
    )
    kept = [c for c in old.get("clips", []) if c["id"] not in {x["id"] for x in clips}]
    order = ["intersection", "traffic", "synthetic", "still"]
    allc = sorted(kept + clips, key=lambda c: order.index(c["id"]) if c["id"] in order else 99)
    index_path.write_text(
        json.dumps(
            {
                "recorded_on": dt.date.today().isoformat(),
                "cpu": cpu_name(),
                "threads": n_threads,
                "device": f"{det.device}" + (f" ({gpu_name()})" if det.device == "cuda" else ""),
                "llm_dtype": getattr(llm, "dtype", None) or old.get("llm_dtype"),
                "detector": detector,
                "stride": stride,
                "note": machine_note,
                "clips": allc,
            },
            indent=2,
            ensure_ascii=False,
        ),
        "utf-8",
    )
    print("wrote", index_path)
